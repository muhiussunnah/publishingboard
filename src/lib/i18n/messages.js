export function translate(lang, key, vars) {
  const dict = messages[lang] || messages[DEFAULT_LANG];
  let str = dict[key] != null ? dict[key] : (messages[DEFAULT_LANG][key] != null ? messages[DEFAULT_LANG][key] : key);
  if (vars) for (const k of Object.keys(vars)) str = str.replaceAll(`{${k}}`, vars[k]);
  return str;
}
